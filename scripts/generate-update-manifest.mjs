import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import packageJson from "../package.json" with { type: "json" };

const GITHUB_RELEASE_URL = "https://github.com/2642475449/Termflow/releases";
const PROJECT_ROOT = resolve(import.meta.dirname, "..");

function readOption(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return undefined;

  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) {
    throw new Error(`${name} needs a value.`);
  }

  return value;
}

function hasOption(name) {
  return process.argv.includes(name);
}

function resolveProjectPath(path) {
  return resolve(PROJECT_ROOT, path);
}

function printUsage() {
  console.log(`Usage: pnpm update:manifest [options]

Creates the signed Tauri updater manifest for a GitHub Release.

Options:
  --version <semver>       Release version (default: package.json version)
  --notes <text>           Release notes shown in the app
  --artifact <path>        Path to the NSIS .exe generated by Tauri
  --signature <path>       Path to the matching .exe.sig file
  --url <https-url>        Public URL of the installer
  --output <path>          Output path for latest.json
  --help                   Show this help
`);
}

if (hasOption("--help")) {
  printUsage();
  process.exit(0);
}

const version = readOption("--version") ?? packageJson.version;
const artifactName = `Termflow_${version}_x64-setup.exe`;
const artifactPath = resolveProjectPath(
  readOption("--artifact") ?? `src-tauri/target/release/bundle/nsis/${artifactName}`,
);
const signaturePath = resolveProjectPath(readOption("--signature") ?? `${artifactPath}.sig`);
const installerUrl = readOption("--url")
  ?? `${GITHUB_RELEASE_URL}/download/v${version}/${artifactName}`;
const outputPath = resolveProjectPath(readOption("--output") ?? "output/updates/latest.json");
const notes = readOption("--notes") ?? `Termflow v${version}`;

if (!URL.canParse(installerUrl) || !installerUrl.startsWith("https://")) {
  throw new Error("--url must be an HTTPS URL.");
}

const [installerStat, signatureStat] = await Promise.all([
  stat(artifactPath),
  stat(signaturePath),
]);

if (signatureStat.mtimeMs < installerStat.mtimeMs) {
  throw new Error(
    `Update signature is older than the installer. Run pnpm tauri:build:signed before generating the manifest.\nInstaller: ${artifactPath}\nSignature: ${signaturePath}`,
  );
}

const signature = (await readFile(signaturePath, "utf8")).trim();
if (!signature) {
  throw new Error(`Update signature is empty: ${signaturePath}`);
}

const manifest = {
  version,
  notes,
  pub_date: new Date().toISOString(),
  platforms: {
    "windows-x86_64": {
      url: installerUrl,
      signature,
    },
  },
};

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

console.log(`Created update manifest: ${outputPath}`);
console.log(`Upload these files to the GitHub Release for v${version}:`);
console.log(`  ${artifactPath} -> ${artifactName}`);
console.log(`  ${outputPath} -> latest.json`);
console.log(`Keep the signature file for release records: ${signaturePath}`);
