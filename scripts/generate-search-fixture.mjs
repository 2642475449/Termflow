import { mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, parse, relative, resolve } from "node:path";
import process from "node:process";

const MARKER_FILE = ".termflow-search-fixture";

function printUsage() {
  console.log(`Usage:
  node scripts/generate-search-fixture.mjs --output <path> [--files 20000] [--matches 100]

The output directory must not be the current directory or a filesystem root.
An existing directory is replaced only when it contains ${MARKER_FILE}.`);
}

function readPositiveInteger(value, option) {
  const parsed = Number.parseInt(value, 10);
  if (!Number.isSafeInteger(parsed) || parsed < 0) {
    throw new Error(`${option} must be a non-negative integer`);
  }
  return parsed;
}

function parseArguments(argv) {
  const options = { files: 20_000, matches: 100, output: null };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--help" || argument === "-h") {
      return { ...options, help: true };
    }
    const value = argv[index + 1];
    if (!value) throw new Error(`Missing value for ${argument}`);
    if (argument === "--output") options.output = value;
    else if (argument === "--files") options.files = readPositiveInteger(value, argument);
    else if (argument === "--matches") options.matches = readPositiveInteger(value, argument);
    else throw new Error(`Unknown option: ${argument}`);
    index += 1;
  }
  return options;
}

async function prepareOutput(output) {
  const target = resolve(output);
  const current = resolve(process.cwd());
  const targetToCurrent = relative(target, current);
  const targetContainsCurrent = targetToCurrent === ""
    || (!targetToCurrent.startsWith("..") && !isAbsolute(targetToCurrent));
  if (targetContainsCurrent || target === parse(target).root) {
    throw new Error("Refusing to use the current directory, its parent, or a filesystem root");
  }

  const marker = join(target, MARKER_FILE);
  try {
    const targetStat = await stat(target);
    if (!targetStat.isDirectory()) {
      throw new Error("Output exists and is not a directory");
    }
    const entries = await readdir(target);
    if (entries.length > 0) {
      const existingMarker = await readFile(marker, "utf8").catch(() => null);
      if (existingMarker?.trim() !== "generated by Termflow search fixture") {
        throw new Error("Output exists but is not a Termflow search fixture");
      }
      await rm(target, { recursive: true, force: true });
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  await mkdir(target, { recursive: true });
  await writeFile(marker, "generated by Termflow search fixture\n");
  return target;
}

async function generateFixture({ output, files, matches }) {
  if (!output) throw new Error("--output is required");
  if (matches > files) throw new Error("--matches cannot exceed --files");
  const target = await prepareOutput(output);
  const batchSize = 256;

  for (let batchStart = 0; batchStart < files; batchStart += batchSize) {
    const tasks = [];
    const batchEnd = Math.min(files, batchStart + batchSize);
    for (let index = batchStart; index < batchEnd; index += 1) {
      const relative = join("src", `module-${Math.floor(index / 500)}`, `file-${index}.ts`);
      const path = join(target, relative);
      const matched = index < matches;
      const body = [
        `export const value${index} = ${index};`,
        matched
          ? `export const wrapper${index} = updateWrapper.eq("id", ${index});`
          : `export const helper${index} = calculateValue(value${index});`,
        "",
      ].join("\n");
      tasks.push(mkdir(dirname(path), { recursive: true }).then(() => writeFile(path, body)));
    }
    await Promise.all(tasks);
  }

  await mkdir(join(target, "node_modules", "fixture-package"), { recursive: true });
  await writeFile(
    join(target, "node_modules", "fixture-package", "ignored.js"),
    "updateWrapper.eq('ignored', true);\n"
  );
  await writeFile(join(target, ".gitignore"), "node_modules/\ndist/\n");

  console.log(JSON.stringify({ output: target, files, matches }, null, 2));
}

try {
  const options = parseArguments(process.argv.slice(2));
  if (options.help) printUsage();
  else await generateFixture(options);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
